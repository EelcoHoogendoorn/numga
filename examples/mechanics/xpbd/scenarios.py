"""Swinging-chain scene setup and standalone runner for extended position-based dynamics."""

from __future__ import annotations

from collections.abc import Callable, Iterable, Iterator
from functools import partial

import numpy as np

from numga import Context, NumpyContext, concatenate, stack
from examples.mechanics.lie_integrators import inertia_from_points
from examples.mechanics.xpbd import core
from examples.mechanics.xpbd.core import Inertia, InverseInertia, Motor, PairPartition, Point, Rate

# Default chain geometry, material parameters, and time-stepping parameters.
n_links = 10
spacing = 9e-2
semi_axes = np.array([0.62, 0.38, 0.22]) * spacing
curl = 0.3
compliance = 1e-9
damping = 1e-3
gravity_acceleration = 0.5
runtime = 4.0
n_steps = 150
n_substeps = 4
dt = runtime / n_steps
frame_duration_ms = 40


# --- math -----------------------------------------------------------------------------
def curved_chain(
    context: Context, n_links: int, spacing: float, semi_axes: np.ndarray, curl: float, gravity_acceleration: float,
) -> tuple[Motor, Rate, Point, Inertia, InverseInertia, Point, list[PairPartition]]:
    """An arc of `n_links` ellipsoidal links starts from rest with red-black joint partitions and a pinned base.

    Body `0` acts as a fixed pin at the origin with zero inverse inertia, followed by `n_links` triaxial ellipsoidal links whose inertia comes from six axial unit masses at `semi_axes * sqrt(3 / 5)`. Neighbouring links meet at anchors `+-spacing / 2` along their local `x`-axis and start along a horizontal arc generated by powers of one neighbour motor. Splitting even and odd joints gives two disjoint partitions whose body pairs relax in parallel.
    """
    mv = context.multivector
    origin = mv.w.dual()                                                        # [] Point-
    n_bodies = n_links + 1

    # Six unit masses placed along the principal axes reproduce the inertia tensor of a solid triaxial ellipsoid.
    offsets = mv.direction(np.eye(3)) * (semi_axes * np.sqrt(3 / 5))            # [3] Point-
    mass_points = concatenate([origin + offsets, origin - offsets])             # [6] Point-
    inertia, inverse_inertia = inertia_from_points(mass_points)                 # [] Forque- <- Rate+, Rate+ <- Forque-

    # Zero mobility pins body 0 at the origin while leaving all moving links unconstrained.
    mobility = np.concatenate([[0], np.ones(n_links)])
    half_shift = (mv.xw * (spacing / 4)).exp()                                  # [] Rotor+
    neighbour = half_shift * (mv.xy * (curl / 2)).exp() * half_shift            # [] Rotor+
    motors = (neighbour.log() * np.arange(n_bodies)).exp().retyped(Motor)       # [n_bodies] Rotor+
    rates = mv.bivector().broadcast_to(n_bodies).retyped(Rate)                  # [n_bodies] Rate+
    first_moments = mass_points.sum(axis=-1)[None].broadcast_to(n_bodies).retyped(Point)   # [n_bodies] Point-
    inertias = inertia[None].broadcast_to(n_bodies)                             # [n_bodies] Forque- <- Rate+
    inverse_inertias = inverse_inertia[None].broadcast_to(n_bodies) * mobility  # [n_bodies] Rate+ <- Forque-
    gravity = mv.direction([0, 0, -gravity_acceleration])                       # [] Point-

    link = np.arange(n_links)
    pairs = np.array([link, link + 1])
    anchors = origin + mv.direction([1, 0, 0]) * (np.array([[0.5], [-0.5]]) * spacing * np.ones(n_links))   # [2, n_links] Point-
    partitions = [(pairs[:, half], anchors[:, half]) for half in (slice(0, None, 2), slice(1, None, 2))]
    return motors, rates, first_moments, inertias, inverse_inertias, gravity, partitions


def swinging_motors_jax(
    n_links: int, n_steps: int, n_substeps: int, dt: float,
) -> Iterator[Motor]:
    """Yields the body poses (`[n_links + 1] Rotor+`) across `n_steps` steps compiled with `jax.jit`."""
    import jax
    from numga.backend.jax import JaxContext

    motors, rates, first_moments, inertias, inverse_inertias, gravity, partitions = curved_chain(
        JaxContext(core.ga), n_links, spacing, semi_axes, curl, gravity_acceleration,
    )
    compiled_step = jax.jit(
        partial(
            core.advance,
            first_moments=first_moments,
            inertias=inertias,
            inverse_inertias=inverse_inertias,
            gravity=gravity,
            compliance=compliance,
            damping=damping,
            partitions=partitions,
            n_substeps=n_substeps,
            dt=dt,
        )
    )
    yield motors
    for _ in range(n_steps):
        motors, rates = compiled_step(motors, rates)
        yield motors


# --- plumbing -------------------------------------------------------------------------
def save_states(
    states: Iterable[Motor], animate: Callable[..., Iterable[np.ndarray]], *arguments, name: str, duration_ms: int,
) -> list[Motor]:
    """Streams `states` once through `animate(*arguments, states)` into `save_animation` and returns the collected states."""
    from examples.util.animation import save_animation

    recorded: list[Motor] = []

    def passing() -> Iterator[Motor]:
        for state in states:
            recorded.append(state)
            yield state

    save_animation(animate(*arguments, passing()), name, duration_ms)
    return recorded


def main() -> None:
    """Runs the swinging XPBD chain, writes `plots/xpbd_chain.gif`, and checks joint closure and pin stationarity."""
    from examples.mechanics.xpbd import render

    context = NumpyContext(core.ga)
    motors, rates, first_moments, inertias, inverse_inertias, gravity, partitions = curved_chain(
        context, n_links, spacing, semi_axes, curl, gravity_acceleration,
    )
    recorded = save_states(
        core.swing_motors(
            motors, rates, first_moments, inertias, inverse_inertias,
            gravity, compliance, damping, partitions, n_steps, n_substeps, dt,
        ),
        render.animate_chain,
        semi_axes,
        spacing,
        name="xpbd_chain",
        duration_ms=frame_duration_ms,
    )
    motor_history = stack(recorded)                                             # [n_steps + 1, ...] Rotor+

    # checks
    origin = context.multivector.w.dual()                                       # [] Point-
    separations = core.joint_separations(motor_history, partitions)             # [n_steps + 1, ...] Scalar+
    pin_drift = ((motor_history[:, 0] >> origin) & origin).norm()               # [n_steps + 1] Scalar+
    assert (separations < 0.1 * spacing).all()
    assert (pin_drift < 1e-6).all()


if __name__ == "__main__":
    main()
